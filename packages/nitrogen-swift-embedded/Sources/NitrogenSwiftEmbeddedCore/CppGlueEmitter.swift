import Foundation
import NitrogenSwiftInputCore

/// Emits the C++ subclass that bridges nitrogen's abstract `HybridFooSpec`
/// (Android shared layer) to Embedded-Swift `@c` symbols.
///
/// User authors `HybridFoo.swift`. nitrogen-swift-spec-input lowers the IR
/// into nitrogen's spec model, which produces `HybridFooSpec.hpp` and
/// `HybridFooSpec.cpp` in `nitrogen/generated/shared/c++/`. This emitter
/// produces `HybridFoo.hpp` — the concrete subclass that overrides each
/// virtual method by forwarding through the opaque handle to `@c` Swift
/// symbols. The user includes this header in their Android CMake target,
/// alongside the `.o` produced by `EmbeddedCompiler`.
public enum CppGlueEmitter {
    public static func emit(_ object: HybridObjectIR, namespace: String) throws -> String {
        let className = object.className
        let specName = "\(className)Spec"

        let externDecls = try (
            ["extern void* \(className)_create();",
             "extern void \(className)_destroy(void* handle);"]
            + object.methods.map { try cExtern(for: $0, on: object) }
        ).joined(separator: "\n")

        let overrides = try object.methods
            .map { try cppOverride(for: $0, on: object) }
            .joined(separator: "\n\n")

        return """
        // Generated by nitrogen-swift-embedded. Do not edit by hand.
        // Source class: \(className)

        #pragma once

        #include "\(specName).hpp"
        #include <cstdint>

        extern "C" {
        \(externDecls)
        }

        namespace \(namespace) {

          class \(className) : public virtual \(specName) {
          public:
            \(className)(): HybridObject(TAG), _handle(\(className)_create()) {}
            ~\(className)() override { \(className)_destroy(_handle); }

          public:
        \(overrides)

          private:
            void* _handle;
          };

        \(closeNamespace(namespace))

        """
    }

    private static func cExtern(for method: MethodIR, on object: HybridObjectIR) throws -> String {
        let symbol = "\(object.className)_\(method.name)"
        let returnSpelling = cBridgeSpelling(method.returnType)
        let paramTypes = (["void* handle"]
            + method.parameters.map { "\(cBridgeSpelling($0.type)) \($0.label)" })
            .joined(separator: ", ")
        return "extern \(returnSpelling) \(symbol)(\(paramTypes));"
    }

    private static func cppOverride(for method: MethodIR, on object: HybridObjectIR) throws -> String {
        let symbol = "\(object.className)_\(method.name)"
        let cppReturn = cppSpelling(method.returnType)
        let paramDecls = method.parameters
            .map { "\(cppSpelling($0.type)) \($0.label)" }
            .joined(separator: ", ")

        let argList = method.parameters
            .map { argCast(label: $0.label, from: $0.type) }
            .joined(separator: ", ")
        let callArgs = (["_handle"] + (argList.isEmpty ? [] : [argList]))
            .joined(separator: ", ")
        let invocation = "\(symbol)(\(callArgs))"

        let body: String
        switch method.returnType {
        case .void:
            body = "      \(invocation);"
        case .float:
            body = "      return static_cast<double>(\(invocation));"
        default:
            body = "      return \(invocation);"
        }

        return """
            \(cppReturn) \(method.name)(\(paramDecls)) override {
        \(body)
            }
        """
    }

    /// Type spelling for the `extern "C"` declaration that matches the @c
    /// bridge signature emitted by `CBridgeEmitter`. IR `float` stays a C
    /// `float` here — the conversion to nitrogen's `double` happens in the
    /// override body.
    private static func cBridgeSpelling(_ type: TypeIR) -> String {
        switch type {
        case .bool: return "bool"
        case .double: return "double"
        case .float: return "float"
        case .int64: return "int64_t"
        case .uint64: return "uint64_t"
        case .void: return "void"
        }
    }

    /// Type spelling for the C++ override — must match what nitrogen produces
    /// in `<HybridFoo>Spec.hpp`. `float` widens to `double` because nitrogen
    /// has no `FloatType` (everything `number` is `double`).
    private static func cppSpelling(_ type: TypeIR) -> String {
        switch type {
        case .bool: return "bool"
        case .double: return "double"
        case .float: return "double"
        case .int64: return "int64_t"
        case .uint64: return "uint64_t"
        case .void: return "void"
        }
    }

    private static func argCast(label: String, from type: TypeIR) -> String {
        switch type {
        case .float: return "static_cast<float>(\(label))"
        default: return label
        }
    }

    private static func closeNamespace(_ namespace: String) -> String {
        return "} // namespace \(namespace)"
    }
}
