import Foundation

/// Emits `<hostLibraryName>+swift-embedded.cmake`, the recipe that compiles
/// each Hybrid's Swift to a no-runtime `.o` at native-build time and adds it to
/// the host library's sources.
///
/// A separate fragment, and one that lives **outside**
/// `nitrogen/generated/`, which is the only tree nitrogen's cleanup sweeps: it
/// snapshots that directory recursively on every run and deletes every file it
/// did not itself generate. Being a separate file is not what saves the recipe
/// (a separate file *inside* that tree was erased just the same); being outside
/// it is. The cost is one `include(...)` line the author adds once.
///
/// Compiling at CMake time rather than ahead of time in the pass buys per-ABI
/// targeting for free and correct incremental rebuilds via `DEPENDS`.
public enum CMakeFragmentEmitter {
    /// `userSwiftDir` is baked in at generate time. It is a `nitro.json`
    /// value, known here, and an env var would make the build depend on shell
    /// state. `NITRO_SWIFTC` stays an env var because the Swift 6.3+ toolchain
    /// path is per-machine.
    public static func emit(
        hostLibraryName: String,
        userSwiftDir: String,
        classNames: [String]
    ) -> String {
        let compileCalls = classNames
            .map { "nitro_compile_embedded_swift(\($0))" }
            .joined(separator: "\n")

        return """
        # \(hostLibraryName)+swift-embedded.cmake
        # Generated by SwiftStitch (nitrogen-swift-embedded alongside). DO NOT EDIT.
        #
        # Add to your CMakeLists.txt, after the nitrogen autolinking include:
        #   include(${CMAKE_SOURCE_DIR}/../swiftstitch/generated/\(hostLibraryName)+swift-embedded.cmake)

        if(NOT DEFINED ENV{NITRO_SWIFTC})
          message(FATAL_ERROR "swift-embedded: NITRO_SWIFTC must point at a Swift 6.3+ swiftc.")
        endif()
        set(_NITRO_SWIFTC $ENV{NITRO_SWIFTC})
        set(_NITRO_USER_SWIFT_DIR "${CMAKE_SOURCE_DIR}/../\(userSwiftDir)")

        if(ANDROID_ABI STREQUAL "arm64-v8a")
          set(_NITRO_EMBEDDED_TARGET "aarch64-none-none-elf")
        elseif(ANDROID_ABI STREQUAL "x86_64")
          set(_NITRO_EMBEDDED_TARGET "x86_64-unknown-none-elf")
        elseif(ANDROID_ABI STREQUAL "armeabi-v7a")
          set(_NITRO_EMBEDDED_TARGET "armv7-none-none-eabi")
        else()
          message(FATAL_ERROR "swift-embedded: unsupported ANDROID_ABI=${ANDROID_ABI}")
        endif()

        set(_NITRO_BRIDGE_DIR "${CMAKE_SOURCE_DIR}/../swiftstitch/generated/swift")

        # The C++ glue headers live in our tree rather than nitrogen's, so they
        # are no longer on nitrogen's include path for free. This is what lets
        # the `#include "Hybrid<Foo>.hpp"` nitrogen writes into <Lib>OnLoad.cpp
        # resolve. Target properties are read at generate time, so this applies
        # to sources the autolinking include added before us.
        target_include_directories(\(hostLibraryName) PRIVATE "${CMAKE_SOURCE_DIR}/../swiftstitch/generated/c++")

        function(nitro_compile_embedded_swift HYBRID_NAME)
          set(OUT_O "${CMAKE_CURRENT_BINARY_DIR}/nitro-swift-embedded/${HYBRID_NAME}.o")
          set(USER_SWIFT "${_NITRO_USER_SWIFT_DIR}/${HYBRID_NAME}.swift")
          set(BRIDGE_SWIFT "${_NITRO_BRIDGE_DIR}/${HYBRID_NAME}+CBridge.swift")
          add_custom_command(
            OUTPUT ${OUT_O}
            COMMAND ${CMAKE_COMMAND} -E make_directory "${CMAKE_CURRENT_BINARY_DIR}/nitro-swift-embedded"
            COMMAND ${_NITRO_SWIFTC}
              -target ${_NITRO_EMBEDDED_TARGET}
              -enable-experimental-feature Embedded
              -enable-experimental-feature CImplementation
              -wmo -parse-as-library -O -c
              -o ${OUT_O}
              ${USER_SWIFT} ${BRIDGE_SWIFT}
            DEPENDS ${USER_SWIFT} ${BRIDGE_SWIFT}
            COMMENT "Embedded Swift (${ANDROID_ABI}): compiling ${HYBRID_NAME} → ${OUT_O}"
            VERBATIM
          )
          set_source_files_properties(${OUT_O} PROPERTIES EXTERNAL_OBJECT TRUE GENERATED TRUE)
          target_sources(\(hostLibraryName) PRIVATE ${OUT_O})
        endfunction()

        \(compileCalls)

        """
    }
}
