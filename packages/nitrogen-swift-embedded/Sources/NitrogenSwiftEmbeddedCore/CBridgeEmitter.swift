import Foundation
import NitrogenSwiftInputCore

/// Emits a `+CBridge.swift` peer file for a HybridObject. Each method becomes
/// an `@c` (Swift 6.3) free function with a fixed prefix, plus `_create` and
/// `_destroy` lifecycle shims that round-trip the instance through an opaque
/// `UnsafeMutableRawPointer` via `Unmanaged`.
///
/// The output is what Embedded Swift compiles to a `.o` file linkable into the
/// Android host `.so`. No Swift runtime needed in `jniLibs/`.
public enum CBridgeEmitter {
    /// Emits the bridge text for a single `HybridObjectIR`. Throws on
    /// constructs Embedded Swift can't represent through a C ABI in the
    /// current scope (none today — primitive subset only).
    public static func emit(_ object: HybridObjectIR) throws -> String {
        var out = String()
        out.append("// Generated by nitrogen-swift-embedded. Do not edit by hand.\n")
        out.append("// Source class: \(object.className)\n")
        out.append("\n")

        out.append(emitCreate(object))
        out.append("\n")
        out.append(emitDestroy(object))

        for method in object.methods {
            out.append("\n")
            out.append(try emitMethod(method, on: object))
        }

        return out
    }

    private static func emitCreate(_ object: HybridObjectIR) -> String {
        let className = object.className
        return """
        @c
        public func \(className)_create() -> UnsafeMutableRawPointer {
            let instance = \(className)()
            return Unmanaged.passRetained(instance).toOpaque()
        }

        """
    }

    private static func emitDestroy(_ object: HybridObjectIR) -> String {
        let className = object.className
        return """
        @c
        public func \(className)_destroy(_ handle: UnsafeMutableRawPointer) {
            Unmanaged<\(className)>.fromOpaque(handle).release()
        }

        """
    }

    private static func emitMethod(_ method: MethodIR, on object: HybridObjectIR) throws -> String {
        let className = object.className
        let symbolName = "\(className)_\(method.name)"

        var paramDecls: [String] = ["_ handle: UnsafeMutableRawPointer"]
        for param in method.parameters {
            paramDecls.append("_ \(param.label): \(param.type.swiftSpelling)")
        }
        let paramList = paramDecls.joined(separator: ", ")

        let returnClause: String
        switch method.returnType {
        case .void:
            returnClause = ""
        default:
            returnClause = " -> \(method.returnType.swiftSpelling)"
        }

        let argList = method.parameters
            .map { "\($0.label): \($0.label)" }
            .joined(separator: ", ")
        let invocation = "instance.\(method.name)(\(argList))"

        // `try!` keeps the C ABI clean for the primitive subset. A
        // thrown error from a HybridObject method aborts — propagation through
        // the bridge is added in a follow-up commit.
        let call: String
        if method.isThrowing {
            call = "try! \(invocation)"
        } else {
            call = invocation
        }

        let body: String
        switch method.returnType {
        case .void:
            body = "    \(call)"
        default:
            body = "    return \(call)"
        }

        return """
        @c
        public func \(symbolName)(\(paramList))\(returnClause) {
            let instance = Unmanaged<\(className)>.fromOpaque(handle).takeUnretainedValue()
        \(body)
        }

        """
    }
}
